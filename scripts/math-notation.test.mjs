import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import vm from "node:vm";
import ts from "typescript";
import React from "react";
import { renderToStaticMarkup } from "react-dom/server";
import * as jsxRuntime from "react/jsx-runtime";

const source = readFileSync(new URL("../lib/math-notation.ts", import.meta.url), "utf8");
const code = ts.transpileModule(source, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS } }).outputText;
const math = {};
vm.runInNewContext(code, { exports: math });
const segments = math.splitMathText("求 \\(\\sqrt{9}+\\frac{1}{2}\\)，再算 √(x+1) 与 3/4。日期 2026/10/19 不变。");
assert.deepEqual(Array.from(segments, item => item.kind), ["text", "math", "text", "math", "text", "math", "text"]);
assert.equal(segments[1].value, "\\sqrt{9}+\\frac{1}{2}");
assert.equal(segments[3].value, "√(x+1)");
assert.equal(segments[5].value, "3/4");
assert.match(segments[6].value, /2026\/10\/19/);
const parsed = math.parseMath(segments[1].value);
assert.equal(parsed.kind, "row");
assert.equal(parsed.children[0].kind, "sqrt");
assert.equal(parsed.children[2].kind, "fraction");
assert.equal(math.parseMath("2/3").kind, "fraction");
assert.equal(math.parseMath("x^2").kind, "sup");
assert.equal(math.splitMathText("旧题 sqrt(2) 和 \\dfrac{3}{5}").filter(item => item.kind === "math").length, 2);
assert.equal(math.parseMath("\\sqrt[3]{8}").degree.value, "3");
const componentSource = readFileSync(new URL("../app/math-text.tsx", import.meta.url), "utf8");
const componentCode = ts.transpileModule(componentSource, { compilerOptions: { target: ts.ScriptTarget.ES2022, module: ts.ModuleKind.CommonJS, jsx: ts.JsxEmit.ReactJSX } }).outputText;
const component = {};
vm.runInNewContext(componentCode, { exports: component, require: name => name === "react" ? React : name === "react/jsx-runtime" ? jsxRuntime : math });
const html = renderToStaticMarkup(React.createElement(component.default, { value: "求 \\(\\sqrt{9}+\\frac{1}{2}\\)；旧题 √2 和 3/4。<script>" }));
assert.match(html, /<math[^>]*>/);
assert.match(html, /<msqrt>/);
assert.match(html, /<mfrac>/);
assert.match(html, /&lt;script&gt;/);
assert(!html.includes("<script>"));
console.log("PASS: delimited and legacy root/fraction parsing, dates and superscripts.");
